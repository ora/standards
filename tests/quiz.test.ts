import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  cardPoints,
  decodeShare,
  encodeShare,
  maxScore,
  openGroup,
  optionOrder,
  pickCards,
  RUN_CAPS,
  RUN_LENGTH,
  safeNext,
} from "@/lib/quiz";
import { getOpenDeck, openCards, statusCard } from "@/lib/quiz-open";
import { type QuizQuestion, quizDeck } from "@/lib/quiz-schema";
import { STATUS_IDS } from "@/lib/schema";
import { getStandards } from "@/lib/standards";

const EM_DASH = String.fromCharCode(0x2014);
const standardIds = new Set(getStandards().map((s) => s.id));

/** The expert deck is kept out of the repository; check it only where it exists. */
const EXPERT_PATH = join(process.cwd(), "private", "quiz-expert.json");
const expert: QuizQuestion[] | undefined = existsSync(EXPERT_PATH)
  ? quizDeck.parse(JSON.parse(readFileSync(EXPERT_PATH, "utf8")))
  : undefined;

/** Problems that span a deck: duplicate ids, unknown standards, house style. */
function deckProblems(deck: QuizQuestion[], prefix: string): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const q of deck) {
    if (seen.has(q.id)) problems.push(`${q.id} appears twice`);
    seen.add(q.id);
    if (!q.id.startsWith(prefix)) problems.push(`${q.id} should start with "${prefix}"`);
    if (q.standard && !standardIds.has(q.standard)) problems.push(`${q.id} names a standard "${q.standard}" that has no page`);
    if (JSON.stringify(q).includes(EM_DASH)) problems.push(`${q.id} has an em dash; use a colon, a semicolon or a new sentence`);
    if (q.options.some((o) => /\b(all|none|both) of the above\b/i.test(o))) problems.push(`${q.id} has an option that depends on order`);
  }
  return problems;
}

describe("content/quiz/open.json", () => {
  it("is a valid deck in the house style", () => {
    expect(deckProblems(openCards(), "o-")).toEqual([]);
  });

  it("has enough cards for a run, with every cap", () => {
    const deck = getOpenDeck();
    expect(deck.length).toBeGreaterThanOrEqual(60);
    const run = pickCards(deck, RUN_LENGTH.open, RUN_CAPS.open, openGroup);
    expect(run).toHaveLength(RUN_LENGTH.open);
    expect(run.filter((q) => openGroup(q) === "status").length).toBeLessThanOrEqual(RUN_CAPS.open.status);
  });

  it("asks one status card per standard, answered by its page", () => {
    for (const s of getStandards()) {
      const card = statusCard(s);
      expect(quizDeck.element.safeParse(card).success, card.id).toBe(true);
      expect(card.answer).toBe(STATUS_IDS.indexOf(s.status));
      expect(card.explain).not.toMatch(/\]\(|`/);
    }
  });
});

describe.runIf(expert)("private/quiz-expert.json", () => {
  const deck = expert ?? [];

  it("is a valid deck in the house style", () => {
    expect(deckProblems(deck, "x-")).toEqual([]);
  });

  it("has enough cards for a run, and shares no id or question with the open deck", () => {
    expect(deck.length).toBeGreaterThanOrEqual(RUN_LENGTH.expert * 3);
    const open = openCards();
    const openIds = new Set(open.map((q) => q.id));
    const openPrompts = new Set(open.map((q) => q.prompt.toLowerCase()));
    expect(deck.filter((q) => openIds.has(q.id) || openPrompts.has(q.prompt.toLowerCase())).map((q) => q.id)).toEqual([]);
  });

  // `npm run quiz:sql` writes the SQL that loads the deck into Supabase.
  it.runIf(process.env.UPDATE_QUIZ_SQL)("writes private/quiz-expert.sql", () => {
    const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
    const rows = deck.map((q) => `  (${quote(q.id)}, ${quote(JSON.stringify(q))}::jsonb, true, now())`);
    const sql = [
      "-- Generated by `npm run quiz:sql` from private/quiz-expert.json. Run it in the Supabase SQL editor.",
      "begin;",
      "insert into public.quiz_questions (id, data, active, updated_at) values",
      `${rows.join(",\n")}`,
      "on conflict (id) do update set data = excluded.data, active = true, updated_at = now();",
      `update public.quiz_questions set active = false where id not in (${deck.map((q) => quote(q.id)).join(", ")});`,
      "commit;",
      "",
    ].join("\n");
    writeFileSync(join(process.cwd(), "private", "quiz-expert.sql"), sql);
  });
});

describe("scoring", () => {
  it("rewards right, fast and in a row, and nothing for wrong", () => {
    expect(cardPoints(false, 1000, 0)).toBe(0);
    expect(cardPoints(true, 1000, 1)).toBe(150);
    expect(cardPoints(true, 3000, 1)).toBe(150);
    expect(cardPoints(true, 20_000, 1)).toBe(100);
    expect(cardPoints(true, 60_000, 1)).toBe(100);
    expect(cardPoints(true, 1000, 3)).toBe(170);
    expect(cardPoints(true, 1000, 40)).toBe(200);
  });

  it("caps a run's score", () => {
    expect(maxScore(1)).toBe(150);
    expect(maxScore(12)).toBeGreaterThan(maxScore(11));
  });
});

describe("share codes", () => {
  it("round-trip", () => {
    const results = [true, false, true, true];
    expect(decodeShare(encodeShare(420, results))).toEqual({ score: 420, results });
  });

  it("reject malformed and impossible scores", () => {
    expect(decodeShare("abc")).toBeUndefined();
    expect(decodeShare("100-")).toBeUndefined();
    expect(decodeShare("100-012")).toBeUndefined();
    expect(decodeShare(`${maxScore(2) + 1}-11`)).toBeUndefined();
  });
});

describe("dealing", () => {
  const card = (id: string, kind: QuizQuestion["kind"]) => ({ id, kind });

  it("respects caps, and fills from skipped cards when it must", () => {
    const deck = [...Array.from({ length: 10 }, (_, i) => card(`f${i}`, "fake")), card("q", "quick")];
    const run = pickCards(deck, 4, { fake: 2 });
    expect(run).toHaveLength(4);
    expect(run.slice(0, 3).filter((c) => c.kind === "fake")).toHaveLength(2);
  });

  it("keeps the written order of a scale or True and False, and shuffles the rest", () => {
    expect(optionOrder({ kind: "real", options: ["a", "b", "c"] })).toEqual([0, 1, 2]);
    expect(optionOrder({ kind: "quick", options: ["True", "False"] })).toEqual([0, 1]);
    expect(optionOrder({ kind: "quick", options: ["a", "b", "c", "d"] }).sort()).toEqual([0, 1, 2, 3]);
  });
});

describe("sign-in return path", () => {
  it("stays on this site", () => {
    expect(safeNext("/play?deck=expert")).toBe("/play?deck=expert");
    expect(safeNext("//evil.example")).toBe("/play");
    expect(safeNext("https://evil.example")).toBe("/play");
    expect(safeNext("/\\evil.example")).toBe("/play");
    expect(safeNext(null)).toBe("/play");
  });
});
